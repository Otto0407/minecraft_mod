package com.otto.monstergirlcompanions.client.model;

import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.Mob;

/**
 * Shared monster girl body: the default LittleMaid ("Orign") model from LittleMaidModelLoader,
 * flattened into HumanoidModel's part layout. 64x32 texture in the LittleMaid layout.
 * The matching Blockbench projects are in {@code blockbench/} (generated by
 * {@code tools/gen_maid_assets.py}).
 */
public class MonsterGirlModel<T extends Mob> extends HumanoidModel<T> {
    /** Distance of the shoulder pivots from the body's centre line. */
    private static final float SHOULDER_OFFSET = 3.0F;

    public MonsterGirlModel(ModelPart root) {
        super(root);
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();

        root.addOrReplaceChild("head", CubeListBuilder.create()
                .texOffs(0, 0).addBox(-4.0F, -8.0F, -4.0F, 8.0F, 8.0F, 8.0F)
                .texOffs(24, 0).addBox(-4.0F, 0.0F, 1.0F, 8.0F, 4.0F, 3.0F)
                .texOffs(24, 18).addBox(-5.0F, -7.0F, 0.2F, 1.0F, 3.0F, 3.0F)
                .texOffs(24, 18).addBox(4.0F, -7.0F, 0.2F, 1.0F, 3.0F, 3.0F)
                .texOffs(52, 10).addBox(-2.0F, -7.2F, 4.0F, 4.0F, 4.0F, 2.0F)
                .texOffs(46, 20).addBox(-1.5F, -6.8F, 4.0F, 3.0F, 9.0F, 3.0F)
                .texOffs(58, 21).addBox(-5.5F, -6.8F, 0.9F, 1.0F, 8.0F, 2.0F)
                .mirror().texOffs(58, 21).addBox(4.5F, -6.8F, 0.9F, 1.0F, 8.0F, 2.0F),
                PartPose.offset(0.0F, 8.0F, 0.0F));
        // HumanoidModel requires a hat part; the maid has none.
        root.addOrReplaceChild("hat", CubeListBuilder.create(), PartPose.offset(0.0F, 8.0F, 0.0F));

        PartDefinition body = root.addOrReplaceChild("body", CubeListBuilder.create()
                .texOffs(32, 8).addBox(-3.0F, 0.0F, -2.0F, 6.0F, 7.0F, 4.0F), PartPose.offset(0.0F, 8.0F, 0.0F));
        body.addOrReplaceChild("skirt", CubeListBuilder.create()
                .texOffs(0, 16).addBox(-4.0F, -2.0F, -4.0F, 8.0F, 8.0F, 8.0F), PartPose.offset(0.0F, 7.0F, 0.0F));

        root.addOrReplaceChild("right_arm", CubeListBuilder.create()
                .texOffs(48, 0).addBox(-2.0F, -1.0F, -1.0F, 2.0F, 8.0F, 2.0F), PartPose.offset(-SHOULDER_OFFSET, 9.6F, 0.0F));
        root.addOrReplaceChild("left_arm", CubeListBuilder.create()
                .texOffs(56, 0).addBox(0.0F, -1.0F, -1.0F, 2.0F, 8.0F, 2.0F), PartPose.offset(SHOULDER_OFFSET, 9.6F, 0.0F));

        root.addOrReplaceChild("right_leg", CubeListBuilder.create()
                .texOffs(32, 19).addBox(-2.0F, 0.0F, -2.0F, 3.0F, 9.0F, 4.0F), PartPose.offset(-1.0F, 15.0F, 0.0F));
        root.addOrReplaceChild("left_leg", CubeListBuilder.create()
                .mirror().texOffs(32, 19).addBox(-1.0F, 0.0F, -2.0F, 3.0F, 9.0F, 4.0F), PartPose.offset(1.0F, 15.0F, 0.0F));

        return LayerDefinition.create(mesh, 64, 32);
    }

    @Override
    public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        super.setupAnim(entity, limbSwing, limbSwingAmount, ageInTicks, netHeadYaw, headPitch);
        // HumanoidModel moves the pivots to vanilla player positions; put them back on the maid body.
        for (ModelPart part : new ModelPart[]{head, hat, body, rightArm, leftArm, rightLeg, leftLeg}) {
            PartPose pose = part.getInitialPose();
            part.setPos(pose.x, pose.y, pose.z);
        }
        // Keep the shoulders following the body twist of the attack swing.
        if (attackTime > 0.0F) {
            float twist = body.yRot;
            rightArm.x = -Mth.cos(twist) * SHOULDER_OFFSET;
            rightArm.z = Mth.sin(twist) * SHOULDER_OFFSET;
            leftArm.x = Mth.cos(twist) * SHOULDER_OFFSET;
            leftArm.z = -Mth.sin(twist) * SHOULDER_OFFSET;
        }
    }
}
